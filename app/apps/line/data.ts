// avatar = รูปใน public (ถ้าไม่ใส่ จะแสดงตัวอักษรตัวแรกบนพื้นไล่สี)
export type Sender = 'me' | 'them';

export type ChatItem =
  | { type: 'date'; label: string }
  | { type: 'msg'; from: Sender; text: string; time: string; read?: boolean; sender?: string };

export interface Member {
  name: string;
  avatar?: string;
  avatarBg?: string;
}

export interface Chat {
  id: number;
  name: string;
  avatar?: string;
  avatarBg?: string;
  time: string; // เวลา/วันที่ที่แสดงในรายการแชท
  unread: number;
  kind: 'friend' | 'group';
  members?: Member[]; // เฉพาะกลุ่ม: สมาชิก "คนอื่น" (ไม่รวมเรา) จำนวนสมาชิก = members.length + 1
  banner?: boolean; // true = เปิดห้องแชทแล้วมีแบนเนอร์แจ้งเตือนเลื่อนลงมาด้านบน
  items: ChatItem[];
  callable?: boolean; // true = กดไอคอนโทรแล้วขึ้นหน้าโทร
}

export const lastText = (c: Chat) => {
  for (let i = c.items.length - 1; i >= 0; i--) {
    const it = c.items[i];
    if (it.type === 'msg') return it.text;
  }
  return '';
};

// ตัวช่วยเขียนบท: m = ข้อความ, d = ป้ายวันที่
//   m('me', 'ข้อความ', '21:15', true)           → ข้อความของเรา (true = Read)
//   m('them', 'ข้อความ', '21:04')               → ข้อความของอีกฝ่าย (แชทเดี่ยว)
//   m('them', 'ข้อความ', '21:04', false, 'jayj') → ข้อความของสมาชิกในกลุ่ม (ระบุชื่อคนส่ง)
const m = (from: Sender, text: string, time: string, read?: boolean, sender?: string): ChatItem => ({
  type: 'msg',
  from,
  text,
  time,
  read,
  sender,
});
const d = (label: string): ChatItem => ({ type: 'date', label });

